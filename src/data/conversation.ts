const createAdditionalMessages = (): Message[] =>
  ADDITIONAL_MESSAGES.flatMap(({ chatId, otherUserId, date, startTime, texts }) => {
    const [startHour, startMinute] = startTime.split(':').map(Number);

    return texts.map((text, index) => {
      const totalMinutes = startHour * 60 + startMinute + index * 2;
      const hour = Math.floor(totalMinutes / 60);
      const minute = totalMinutes % 60;
      const time = `${String(hour).padStart(2, '0')}:${String(minute).padStart(2, '0')}`;
      const isMe = index % 2 === 0;

      return {
        id: `m_extra_${chatId}_${index + 1}`,
        chatId,
        senderId: isMe ? CURRENT_USER_ID : otherUserId,
        text,
        type: 'text',
        timestamp: date ? `${date} ${time}` : time,
        isMe,
        ...(isMe ? { status: 'delivered' as const } : {}),
      };
    });
  });

