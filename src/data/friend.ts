// Helper generator function to produce 'count' items programmatically for deep scroll testing
export const generateMockRequests = (count: number): FriendRequest[] => {
  const sampleNames = [
    'Alex Rivera', 'Brenda Song', 'Christopher Nolan', 'Diana Prince',
    'Ethan Hunt', 'Fiona Gallagher', 'George Clark', 'Hannah Abbott',
  ];
  const sampleAvatars = [
    'https://images.unsplash.com/photo-1507003211169-0a1dd7228f2d?w=150',
    'https://images.unsplash.com/photo-1534528741775-53994a69daeb?w=150',
    'https://images.unsplash.com/photo-1539571696357-5a69c17a67c6?w=150',
    'https://images.unsplash.com/photo-1544005313-94ddf0286df2?w=150',
  ];

  return Array.from({ length: count }, (_, index) => {
    const nameIndex = index % sampleNames.length;
    const avatarIndex = index % sampleAvatars.length;
    const mutualCount = Math.floor(Math.random() * 10);

    return {
      id: `gen_req_${index + 1}`,
      name: `${sampleNames[nameIndex]} ${index + 1}`,
      avatarUrl: sampleAvatars[avatarIndex],
      timestamp: `${(index % 50) + 1} w`,
      mutualFriendsCount: mutualCount,
      mutualFriendAvatars: mutualCount > 0 ? [sampleAvatars[(avatarIndex + 1) % sampleAvatars.length]] : [],
    };
  });
};